    private fun grammar(text: String) = japaneseGrammar(japaneseMorphemes(analyzer, text))

    @Test
    fun everyCataloguePointIsFoundInItsExampleSentence() {
        val missed =
            EXAMPLES.filter { (meaning, sentence) -> grammar(sentence).none { meaning in it.meanings } }
        assertTrue("Not found: ${missed.joinToString { "${it.first} in ${it.second}" }}", missed.isEmpty())
    }

    @Test
    fun everyCataloguePointHasAnExampleAndItsOwnMeaning() {
        val catalogueMeanings = GRAMMAR_CATALOGUE.flatMap { it.meanings }
        assertEquals(catalogueMeanings.size, catalogueMeanings.toSet().size)
        assertEquals(catalogueMeanings.toSet(), EXAMPLES.map { it.first }.toSet())
    }

    @Test
    fun theCatalogueCoversEveryJlptLevel() {
        val levels = GRAMMAR_CATALOGUE.groupingBy { it.level }.eachCount()
        assertEquals(JlptLevel.entries.toSet(), levels.keys)
        assertTrue(GRAMMAR_CATALOGUE.size >= 300)
    }

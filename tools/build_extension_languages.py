"""Generates browser-extension/data/languages.js from the app's translation language list.

    python3 -I tools/build_extension_languages.py "$(git rev-parse --short HEAD)"

Reads TranslationLanguages.all in translation/TranslationLanguages.kt, so the extension offers the app's languages
in the app's order with the app's codes ("zh" for Simplified Chinese, "zh-TW" for Traditional).
"""

import json
import re
import sys

SOURCE = "app/src/main/java/com/kienhoang/dualsubreplay/translation/TranslationLanguages.kt"


def main(commit):
    text = open(SOURCE, encoding="utf-8").read()
    body = text[text.index("val all: List<TranslationLanguageOption> = listOf(") :]
    body = body[: body.index("\n    )\n")]
    languages = re.findall(r'TranslationLanguageOption\("([^"]+)", "([^"]+)"', body)
    if len(languages) < 100 or len({code for code, _ in languages}) != len(languages):
        sys.exit(f"Unexpected language list: {len(languages)} entries")
    with open("browser-extension/data/languages.js", "w", encoding="utf-8", newline="\n") as f:
        f.write(
            f"// Generated by tools/build_extension_languages.py from the app (dual-sub-replay {commit}):\n"
            "// TranslationLanguages.all in translation/TranslationLanguages.kt. Do not edit: run the script.\n"
            '// [code, English name], in the app\'s order. The app keeps "zh" for Simplified Chinese; Google calls it "zh-CN".\n'
            "const TRANSLATION_LANGUAGES = [\n"
        )
        for code, name in languages:
            f.write(f"  {json.dumps([code, name], ensure_ascii=False)},\n")
        f.write("];\n\nglobalThis.DualSub = Object.assign(globalThis.DualSub || {}, { TRANSLATION_LANGUAGES });\n")
    print(f"{len(languages)} languages")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])

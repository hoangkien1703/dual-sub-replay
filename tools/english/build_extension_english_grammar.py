"""Generates browser-extension/data/english-grammar.js and the grammar test examples from the Android app's source.

    python3 -I tools/english/build_extension_english_grammar.py . "$(git rev-parse --short HEAD)"

Reads data/EnglishGrammarCatalogue.kt (levels, forms, patterns), ui/LearnerGrammarText.kt and
res/values/strings_grammar_en.xml (each point's English text) and EnglishGrammarCatalogueTest.kt (one example
sentence per point), so the extension's 172 points stay the Android app's own.
"""

import json
import re
import sys

KT = "app/src/main/java/com/kienhoang/dualsubreplay"


def kotlin_string(text):
    return json.loads('"' + text + '"')  # Kotlin's escapes here (\" \\ \u) are JSON's


def android_string(text):
    text = text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")
    return text.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")


def main(repo, commit):
    catalogue_source = open(f"{repo}/{KT}/data/EnglishGrammarCatalogue.kt", encoding="utf-8").read()
    string_lit = r'"((?:[^"\\]|\\.)*)"'
    catalogue = [
        [level.upper(), kotlin_string(form), kotlin_string(spec), meaning]
        for level, form, spec, meaning in re.findall(
            rf"\b(a1|a2|b1|b2)\(\s*{string_lit},\s*{string_lit},\s*GrammarMeaning\.(EN_\w+),?\s*\)", catalogue_source
        )
    ]
    names = dict(re.findall(r"GrammarMeaning\.(EN_\w+) to R\.string\.(\w+)", open(f"{repo}/{KT}/ui/LearnerGrammarText.kt", encoding="utf-8").read()))
    strings = {
        name: android_string(text)
        for name, text in re.findall(r'<string name="(\w+)">(.*?)</string>', open(f"{repo}/app/src/main/res/values/strings_grammar_en.xml", encoding="utf-8").read(), re.S)
    }
    texts = {meaning: strings[name] for meaning, name in sorted(names.items()) if name in strings}
    missing = sorted({m for *_, m in catalogue} - texts.keys())
    if missing:
        sys.exit(f"No text for {missing}")

    test = open(f"{repo}/app/src/test/java/com/kienhoang/dualsubreplay/data/EnglishGrammarCatalogueTest.kt", encoding="utf-8").read()
    examples = [[meaning, kotlin_string(sentence)] for meaning, sentence in re.findall(rf"GrammarMeaning\.(EN_\w+) to {string_lit}", test)]

    header = (
        f"// Generated by tools/english/build_english_grammar.py from the Android app (dual-sub-replay {commit}):\n"
        "// data/EnglishGrammarCatalogue.kt and res/values/strings_grammar_en.xml. Do not edit: run the script.\n"
        "// Each point: [CEFR level, form, pattern (syntax in data/english-grammar-match.js), meaning].\n"
    )
    with open("browser-extension/data/english-grammar.js", "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        f.write("const ENGLISH_GRAMMAR_CATALOGUE = [\n")
        for point in catalogue:
            f.write(f"  {json.dumps(point, ensure_ascii=False)},\n")
        f.write("];\n\n// Each meaning's English explanation.\nconst ENGLISH_GRAMMAR_TEXT = {\n")
        for meaning, text in texts.items():
            f.write(f"  {meaning}: {json.dumps(text, ensure_ascii=False)},\n")
        f.write("};\n\nglobalThis.DualSub = Object.assign(globalThis.DualSub || {}, { ENGLISH_GRAMMAR_CATALOGUE, ENGLISH_GRAMMAR_TEXT });\n")
    with open("browser-extension/test/english-grammar-examples.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump({"source": f"dual-sub-replay {commit} EnglishGrammarCatalogueTest.kt", "examples": examples}, f, ensure_ascii=False, indent=0)
        f.write("\n")
    print(f"{len(catalogue)} patterns, {len(texts)} texts, {len(examples)} examples")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
